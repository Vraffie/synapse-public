"""View model for multi-repository runs (ADR 026): read-only, Qt-free, tolerant of missing fields, fail-closed on validity.

The daemon routes are proposals (see ``multirepo_routes``); the response envelopes below are this client's reading
of ADR 026 D2/D4/D6/D8/D10 and are kept deliberately loose so a renamed or absent field degrades to "-" or "unknown"
instead of an error. Field names inside the envelopes are taken verbatim from the ADR tables.

A manifest is only ever summarised as "valid" when every check here passed: the daemon answered with the manifest
that was asked for, it returned an invalidation list and that list is empty, the run's bindings and the manifest agree
on the repository set and on each repository's access, and the local structure checks passed. Anything missing,
malformed or contradictory makes it "unknown", "not usable" or "invalidated", never "valid".

Every value that reaches a label is untrusted daemon (and, for diffs, agent) output. This module only reads an
allowlist of keys, validates ids, refs and SHAs against fixed patterns, removes control, format (bidi, zero-width),
separator, private-use and surrogate characters, collapses whitespace in single-line fields, and bounds every string,
list and diff. In a diff, removed characters are replaced by a visible marker and counted. Nothing here executes,
renders markup or follows a path.

Assumed envelopes (ADR 026 does not define them; see docs/operations/desktop-console.md):

- ``GET /runs/{id}/repos``: ``{"run_id", "bindings_sha256", "repos" (or "bindings"): [run_repo_bindings row, plus an
  optional "deploy" snapshot of the registry marker], "attempt_worktrees": [row], "commits" (or
  "attempt_repo_commits"): [row]}``
- ``GET /runs/{id}/candidate-manifests``: ``{"manifests": [{"manifest_sha256", "version", "seq", "created_at",
  "invalidations": [{"reason", "actor", "at"}]}]}``
- ``GET /runs/{id}/candidate-manifests/{sha}``: ``{"manifest_sha256", "manifest": <manifest v1 or v2 object>,
  "invalidations": [...], "diffs": [{"repo_id", "diff", "truncated"}]}``
"""
from __future__ import annotations

import hashlib
import re
import unicodedata

MAX_REPOS = 16  # ADR 026 D1 / D8 limit; more rows than this are dropped and counted
MAX_ROWS = 200  # worktree and commit rows read per response
MAX_INVALIDATIONS = 20
MAX_VALIDATIONS = 32
MAX_MANIFESTS = 100
MAX_DIFF_CHARS = 60000
MAX_DIFF_LINES = 4000
MAX_TEXT = 200
STALE_LIMIT = 3  # consecutive refresh failures after which a shown manifest's validity is downgraded to unknown

DEPLOY_NONE_TEXT = "generated by the pipeline, not deployed by Synapse"
UNCHANGED_TEXT = "unchanged (candidate = baseline)"
READ_TEXT = "read only (pinned baseline)"
MARKER = "�"  # shown in place of each removed character in a diff
REQUIRED_VALIDATIONS = ("paths_editable", "xml_well_formed")  # ADR 026 D8: exactly these, both passed

COMMIT_STATES = {  # ADR 026 D6 / D10 attempt_repo_commits.state
    "intent": "commit in progress",
    "done": "changed",
    "unchanged": UNCHANGED_TEXT,
    "failed": "commit failed",
    "not_done": "not committed",
    "unknown": "unknown after a crash (needs recovery)",
}
INVALIDATION_REASONS = {  # ADR 026 D2 / D10 candidate_manifest_invalidations.reason
    "baseline_moved": "a baseline ref moved after the run pinned it",
    "candidate_invalid": "a candidate commit is no longer valid",
    "operator": "invalidated by the operator",
}

_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}")
_REF = re.compile(r"refs/(?:[A-Za-z0-9._-]+/)*[A-Za-z0-9._-]+")
_SHA = re.compile(r"[0-9a-f]{40}|[0-9a-f]{64}")
_SHA256 = re.compile(r"[0-9a-f]{64}")
_UNSAFE_CATEGORIES = frozenset({"Cc", "Cf", "Zl", "Zp", "Co", "Cs", "Cn"})
_UNSAFE_EXTRA = re.compile(
    "[­᠎  ⁠-⁤︀-️￹-￻\U000e0000-\U000e007f\U000e0100-\U000e01ef]")
_SPACE = re.compile(r"\s+")


def _unsafe(ch: str) -> bool:
    return unicodedata.category(ch) in _UNSAFE_CATEGORIES or _UNSAFE_EXTRA.match(ch) is not None


def _strip(value: str, keep: str = "") -> tuple[str, int]:
    """Remove unsafe characters except those in ``keep``; returns (text, removed count)."""
    out, removed = [], 0
    for ch in value:
        if ch in keep or not _unsafe(ch):
            out.append(ch)
        else:
            removed += 1
    return "".join(out), removed


def line(value, limit: int = MAX_TEXT) -> str:
    """Single-line plain text: unsafe characters removed, any whitespace run (newlines, tabs) collapsed to one space."""
    if not isinstance(value, str):
        return ""
    cleaned, _ = _strip(_SPACE.sub(" ", value[:limit * 4]))
    return _SPACE.sub(" ", cleaned).strip()[:limit]


def ident(value) -> str | None:
    return value if isinstance(value, str) and _ID.fullmatch(value) else None


def ref(value) -> str | None:
    if isinstance(value, str) and len(value) <= 200 and _REF.fullmatch(value) and ".." not in value:
        return value
    return None


def sha(value) -> str | None:
    return value if isinstance(value, str) and _SHA.fullmatch(value) else None


def short(value: str | None) -> str:
    return value[:12] if value else "-"


def _int(value) -> int | None:
    return value if type(value) is int and value >= 0 else None


def _rows(value, limit: int = MAX_ROWS) -> list[dict]:
    return [row for row in value[:limit] if isinstance(row, dict)] if isinstance(value, list) else []


def _first(raw: dict, *keys):
    for key in keys:
        if key in raw:
            return raw[key]
    return None


def _order(row: dict, index: int) -> tuple:
    """Newest-last ordering for append-only rows: (attempt_no, seq), then response order as the tie-break."""
    attempt, seq = _int(row.get("attempt_no")), _int(row.get("seq"))
    return (-1 if attempt is None else attempt, -1 if seq is None else seq, index)


# ------------------------------------------------------------------ sanitizers (None = shape not understood)
def sanitize_run_repos(raw, run_id: str | None = None) -> dict | None:
    """``GET /runs/{id}/repos``: bindings (the run's repository set), the current worktree and commit state per repo."""
    if not isinstance(raw, dict):
        return None
    bindings_raw = _first(raw, "repos", "bindings")
    if not isinstance(bindings_raw, list):
        return None
    if run_id is not None and raw.get("run_id") is not None and raw.get("run_id") != run_id:
        return None
    bindings, dropped = {}, 0
    for row in bindings_raw[:MAX_ROWS]:
        repo_id = ident(row.get("repo_id")) if isinstance(row, dict) else None
        if repo_id is None or repo_id in bindings or len(bindings) >= MAX_REPOS:
            dropped += 1
            continue
        writer = row.get("writer_task_id")
        if row.get("access") in ("read", "write"):
            access = row["access"]
        elif "writer_task_id" in row and writer is None:
            access = "read"
        else:
            access = "write" if isinstance(writer, str) and writer else "unknown"
        deploy = row.get("deploy")
        bindings[repo_id] = {"repo_id": repo_id, "access": access, "baseline_ref": ref(row.get("baseline_ref")),
                             "baseline_sha": sha(row.get("baseline_sha")), "writer_task_id": line(writer, 128) or None,
                             # the run's snapshot of the registry marker (ADR 026 D1); absent = no marker
                             "deploy_none": deploy == "none", "deploy_odd": deploy is not None and deploy != "none"}
    dropped += max(0, len(bindings_raw) - MAX_ROWS)
    worktrees = {}
    for _, row in sorted(((_order(r, i), r) for i, r in enumerate(_rows(raw.get("attempt_worktrees")))), key=lambda p: p[0]):
        repo_id = ident(row.get("repo_id"))
        if repo_id is not None:
            worktrees[repo_id] = {"branch": line(row.get("branch"), MAX_TEXT)}
    commits = {}
    for _, row in sorted(((_order(r, i), r) for i, r in enumerate(_rows(_first(raw, "commits", "attempt_repo_commits")))),
                         key=lambda p: p[0]):
        repo_id, state = ident(row.get("repo_id")), row.get("state")
        if repo_id is not None and isinstance(state, str):
            commits[repo_id] = {"state": state if state in COMMIT_STATES else "other", "raw_state": line(state, 40),
                                "candidate_sha": sha(row.get("candidate_sha")), "reason": line(row.get("reason"), MAX_TEXT)}
    return {"bindings_sha256": sha(raw.get("bindings_sha256")), "bindings": bindings, "worktrees": worktrees,
            "commits": commits, "dropped": dropped}


def _invalidations(value) -> list[dict] | None:
    """None = the daemon did not say (unknown). Every list element counts, even a malformed one (fail closed)."""
    if not isinstance(value, list):
        return None
    out = []
    for row in value[:MAX_INVALIDATIONS]:
        reason = row.get("reason") if isinstance(row, dict) else None
        if isinstance(reason, str) and reason in INVALIDATION_REASONS:
            out.append({"reason": reason, "text": INVALIDATION_REASONS[reason]})
        else:
            shown = line(reason, 60) if isinstance(reason, str) else ""
            out.append({"reason": "other", "text": "invalidated (unrecognised reason: " + (shown or "none given") + ")"})
    if len(value) > MAX_INVALIDATIONS:
        out.append({"reason": "other", "text": f"{len(value) - MAX_INVALIDATIONS} more invalidations not shown"})
    return out


def sanitize_manifest_list(raw) -> list[dict] | None:
    """``GET /runs/{id}/candidate-manifests``: unique SHAs, newest last (by ``seq`` when present, else response order)."""
    if not isinstance(raw, dict) or not isinstance(raw.get("manifests"), list):
        return None
    out, seen = [], set()
    for index, row in enumerate(_rows(raw["manifests"], MAX_MANIFESTS)):
        digest = row.get("manifest_sha256")
        if isinstance(digest, str) and _SHA256.fullmatch(digest) and digest not in seen:
            seen.add(digest)
            seq = _int(row.get("seq"))
            out.append({"manifest_sha256": digest, "version": _int(row.get("version")), "order": (-1 if seq is None else seq, index),
                        "invalidations": _invalidations(row.get("invalidations"))})
    out.sort(key=lambda m: m["order"])
    return out


def sanitize_diff(value, truncated_flag=False) -> dict:
    """Untrusted agent diff: plain text, at most MAX_DIFF_LINES lines and MAX_DIFF_CHARS characters.

    Removed characters (control, bidi, zero-width, ...) are replaced by MARKER and counted in ``altered``, so the
    shown text never silently differs from the daemon's text."""
    raw = value if isinstance(value, str) else ""
    head = raw[:MAX_DIFF_CHARS * 2].replace("\r\n", "\n")
    out, altered = [], 0
    for ch in head:
        if ch in "\n\t" or not _unsafe(ch):
            out.append(ch)
        else:
            out.append(MARKER)
            altered += 1
    cleaned = "".join(out)
    lines = cleaned.split("\n")
    truncated = truncated_flag is True or len(raw) > MAX_DIFF_CHARS * 2 or len(cleaned) > MAX_DIFF_CHARS or len(lines) > MAX_DIFF_LINES
    shown = "\n".join(lines[:MAX_DIFF_LINES])[:MAX_DIFF_CHARS]
    return {"text": shown, "truncated": truncated, "altered": altered,
            "raw_sha256": hashlib.sha256(raw.encode("utf-8", "surrogatepass")).hexdigest()}


def _validations(value) -> list[dict]:
    out = []
    for row in _rows(value, MAX_VALIDATIONS):
        name = ident(row.get("name"))
        if name is not None:
            outcome = row.get("outcome")
            out.append({"name": name, "outcome": outcome if outcome in ("passed", "failed", "skipped") else "unknown"})
    return out


def sanitize_manifest_detail(raw, run_id: str | None = None) -> dict | None:
    """``GET /runs/{id}/candidate-manifests/{sha}``: manifest v1 or v2 plus diffs, invalidations and local findings.

    ``problems`` are what this client could check without the canonical bytes (it never claims the hash is right)."""
    if not isinstance(raw, dict):
        return None
    manifest = raw.get("manifest") if isinstance(raw.get("manifest"), dict) else raw
    digest = raw.get("manifest_sha256")
    if not isinstance(manifest.get("repos"), list) or not (isinstance(digest, str) and _SHA256.fullmatch(digest)):
        return None
    version = _int(manifest.get("v"))
    problems = []
    if version not in (1, 2):
        problems.append("unknown manifest version")
    if run_id is not None and manifest.get("run_id") != run_id:
        problems.append("manifest names a different run")
    diffs = {}
    for row in _rows(raw.get("diffs"), MAX_REPOS):
        repo_id = ident(row.get("repo_id"))
        if repo_id is not None and repo_id not in diffs:
            diffs[repo_id] = sanitize_diff(row.get("diff"), row.get("truncated"))
    entries, ids = [], []
    for row in manifest["repos"][:MAX_REPOS * 4]:
        repo_id = ident(row.get("repo_id")) if isinstance(row, dict) else None
        if repo_id is None:
            problems.append("an entry has no valid repo_id")
            continue
        ids.append(repo_id)
        access = row.get("access") if row.get("access") in ("read", "write") else ("write" if version == 1 else "unknown")
        baseline, candidate = sha(row.get("baseline_sha")), sha(row.get("candidate_sha"))
        source = row.get("source") if isinstance(row.get("source"), dict) else {}
        diff_sha = row.get("diff_sha256") if isinstance(row.get("diff_sha256"), str) and _SHA256.fullmatch(row["diff_sha256"]) else None
        diff = diffs.get(repo_id)
        if diff is not None:  # an untruncated diff whose UTF-8 hash equals diff_sha256 is the diff the manifest binds
            diff = dict(diff, verified=(not diff["truncated"] and diff_sha is not None and diff["raw_sha256"] == diff_sha))
        validations = _validations(row.get("validations"))
        entries.append({"repo_id": repo_id, "access": access, "baseline_ref": ref(row.get("baseline_ref")), "baseline_sha": baseline,
                        "candidate_sha": candidate, "unchanged": access == "write" and baseline is not None and baseline == candidate,
                        "source_task": line(source.get("task_id"), 128) or None, "source_attempt": _int(source.get("attempt_no")),
                        "diff_sha256": diff_sha, "diff_bytes": _int(row.get("diff_bytes")), "changed_paths": _int(row.get("changed_paths")),
                        "validations": validations, "diff": diff})
        if access == "unknown":
            problems.append(f"{repo_id}: access is neither read nor write")
        if access == "write" and version == 2:
            if sorted(v["name"] for v in validations) != sorted(REQUIRED_VALIDATIONS) or any(v["outcome"] != "passed" for v in validations):
                problems.append(f"{repo_id}: validations are not exactly paths_editable and xml_well_formed, both passed")
            if candidate is None or baseline is None:
                problems.append(f"{repo_id}: baseline or candidate SHA missing")
        elif access == "write" and any(v["outcome"] != "passed" for v in validations):
            problems.append(f"{repo_id}: a validation did not pass")
    if len(manifest["repos"]) > MAX_REPOS:
        problems.append(f"more than {MAX_REPOS} repositories")
    if ids != sorted(ids) or len(set(ids)) != len(ids):
        problems.append("repositories are not sorted by repo_id or not unique")
    writes = [e for e in entries if e["access"] == "write"]
    if version == 2 and writes and all(e["unchanged"] for e in writes):
        problems.append("no write repository changed (no_changes)")
    return {"manifest_sha256": digest, "version": version, "bindings_sha256": sha(manifest.get("bindings_sha256")),
            "entries": entries, "invalidations": _invalidations(raw.get("invalidations")), "problems": problems}


# ------------------------------------------------------------------ composition
def _state(entry: dict | None, commit: dict | None, access: str) -> tuple[str, str]:
    if entry is not None and entry["access"] == "write" and entry["candidate_sha"] is not None:
        return ("unchanged", UNCHANGED_TEXT) if entry["unchanged"] else ("changed", "changed")
    if access == "read":
        return "read", READ_TEXT
    if commit is not None:
        label = COMMIT_STATES.get(commit["state"], "state " + (commit["raw_state"] or "unknown"))
        if commit["state"] == "failed" and commit["reason"]:
            label += ": " + commit["reason"]
        return commit["state"], label
    return "pending", "no commit yet"


def _deploy(binding: dict | None, state: str, access: str) -> str:
    """Deploy column from the RUN's binding snapshot only (ADR 026 D1, D9); never inferred from the live registry."""
    if access == "read":
        return "-"
    if state == "unchanged":
        return "not deployed (unchanged)"
    if state != "changed":
        return "-"
    if binding is None or binding["deploy_odd"]:
        return "unknown"
    return DEPLOY_NONE_TEXT if binding["deploy_none"] else "target not known here"


def build_view(run_repos: dict | None, manifests: list[dict] | None, detail: dict | None,
               requested_sha: str | None = None, errors: tuple | list = ()) -> dict:
    """Merge the sanitized reads into per-repository rows plus a manifest summary.

    ``requested_sha`` is the manifest the detail was asked for; an answer for another manifest is never trusted.
    ``visible`` is True for a run with more than one repository, with a manifest, or with a response this client did
    not understand; a single-repository run on an old daemon (every route 404) keeps today's agent pane alone."""
    bindings = (run_repos or {}).get("bindings") or {}
    commits = (run_repos or {}).get("commits") or {}
    worktrees = (run_repos or {}).get("worktrees") or {}
    problems = []
    if detail is not None and requested_sha is not None and detail["manifest_sha256"] != requested_sha:
        problems.append("the daemon answered with a different manifest than the one requested")
        detail = None
    entries = {e["repo_id"]: e for e in (detail or {}).get("entries", [])}
    if detail is not None and bindings:
        only_run, only_manifest = sorted(set(bindings) - set(entries)), sorted(set(entries) - set(bindings))
        if only_run or only_manifest:
            problems.append("repository set differs between the run and the manifest (only in run: "
                            + (", ".join(only_run) or "none") + "; only in manifest: " + (", ".join(only_manifest) or "none") + ")")
        for repo_id in sorted(set(bindings) & set(entries)):
            run_access, manifest_access = bindings[repo_id]["access"], entries[repo_id]["access"]
            if run_access != manifest_access:
                problems.append(f"{repo_id}: access differs (run: {run_access}, manifest: {manifest_access})")
        if run_repos.get("bindings_sha256") and detail["bindings_sha256"] and run_repos["bindings_sha256"] != detail["bindings_sha256"]:
            problems.append("bindings_sha256 differs from the run's bindings")
    rows = []
    for repo_id in sorted(set(bindings) | set(entries))[:MAX_REPOS]:
        binding, entry = bindings.get(repo_id), entries.get(repo_id)
        run_access = (binding or {}).get("access")
        access = entry["access"] if entry is not None and entry["access"] != "unknown" else (run_access or "unknown")
        state, label = _state(entry, commits.get(repo_id), access)
        mismatch = entry is not None and run_access is not None and run_access != entry["access"]
        rows.append({"repo_id": repo_id, "access": access, "access_text": f"{access} (run says {run_access})" if mismatch else access,
                     "state": state, "label": label,
                     "baseline_ref": (binding or {}).get("baseline_ref") or (entry or {}).get("baseline_ref"),
                     "baseline_sha": (binding or {}).get("baseline_sha") or (entry or {}).get("baseline_sha"),
                     "candidate_sha": (entry or {}).get("candidate_sha"), "deploy_none": bool((binding or {}).get("deploy_none")),
                     "deploy": _deploy(binding, state, access), "branch": (worktrees.get(repo_id) or {}).get("branch") or "",
                     "changed_paths": (entry or {}).get("changed_paths"), "diff_bytes": (entry or {}).get("diff_bytes"),
                     "validations": (entry or {}).get("validations") or [], "diff": (entry or {}).get("diff")})
    manifest = None
    listed = next((m for m in manifests or [] if m["manifest_sha256"] == requested_sha), None) if requested_sha else None
    if listed is None and manifests:
        listed = manifests[-1]
    if detail is not None or listed is not None:
        known = [inv for inv in ((detail or {}).get("invalidations"), (listed or {}).get("invalidations")) if inv is not None]
        invalidations = [i for inv in known for i in inv]
        all_problems = problems + ((detail or {}).get("problems") or [])
        if detail is None and not problems:
            all_problems.append("manifest detail not available")
        if invalidations:
            validity = "invalidated"
        elif not known:
            validity = "unknown"
            all_problems.append("the daemon did not report invalidations")
        elif all_problems:
            validity = "problems"
        else:
            validity = "valid"
        manifest = {"manifest_sha256": (detail or listed)["manifest_sha256"],
                    "version": (detail or listed)["version"], "invalidations": invalidations, "problems": all_problems[:20],
                    "count": len(manifests or []), "validity": validity}
    elif problems:
        manifest = {"manifest_sha256": requested_sha, "version": None, "invalidations": [], "problems": problems,
                    "count": len(manifests or []), "validity": "problems"}
    return {"visible": len(rows) > 1 or manifest is not None or bool(errors), "rows": rows, "manifest": manifest,
            "dropped": (run_repos or {}).get("dropped", 0), "errors": list(errors), "stale": None,
            "bindings_sha256": (run_repos or {}).get("bindings_sha256")}


def mark_stale(view: dict, since: str, failures: int) -> dict:
    """The last good view after ``failures`` consecutive refresh failures: flagged, and validity downgraded to unknown
    once STALE_LIMIT is reached (an invalidation that happened meanwhile would otherwise stay hidden behind 'valid')."""
    stale = dict(view, stale=f"could not refresh since {since} ({failures} failed attempts)")
    if failures >= STALE_LIMIT and stale.get("manifest") and stale["manifest"]["validity"] == "valid":
        stale["manifest"] = dict(stale["manifest"], validity="unknown",
                                 problems=stale["manifest"]["problems"] + ["could not refresh; validity unknown"])
    return stale


def manifest_summary(manifest: dict | None) -> tuple[str, str]:
    """(headline, banner) plain text for the manifest; banner is '' unless the manifest must not be acted on."""
    if manifest is None:
        return "No candidate manifest yet.", ""
    version = manifest["version"] if manifest["version"] is not None else "?"
    head = f"Candidate manifest {short(manifest['manifest_sha256'])} (v{version})"
    if manifest["count"] > 1:
        head += f", newest of {manifest['count']}"
    if manifest["validity"] == "invalidated":
        reasons = "; ".join(sorted({i["text"] for i in manifest["invalidations"]}))
        return head + ": INVALIDATED", "This manifest is invalidated and cannot be approved or deployed: " + reasons + "."
    if manifest["validity"] == "problems":
        return head + ": not usable", "This view found problems in the manifest: " + "; ".join(manifest["problems"]) + "."
    if manifest["validity"] == "unknown":
        return head + ": validity unknown", "Do not act on this manifest yet: " + "; ".join(manifest["problems"]) + "."
    return head + ": valid (no invalidation recorded by the daemon)", ""
