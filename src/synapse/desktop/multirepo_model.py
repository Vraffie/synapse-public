"""View model for multi-repository runs (ADR 026): read-only, Qt-free, tolerant of missing fields.

The daemon routes are proposals (see ``multirepo_routes``); the response envelopes below are this client's reading
of ADR 026 D1/D2/D4/D6/D8/D10 and are kept deliberately loose so a renamed or absent field degrades to "-" instead of
an error. Field names inside the envelopes are taken verbatim from the ADR tables.

Every value that reaches a label is untrusted daemon (and, for diffs, agent) output. This module only reads an
allowlist of keys, validates ids, refs and SHAs against fixed patterns, strips control and bidirectional-override
characters, and bounds every string, list and diff. Nothing here executes, renders markup or follows a path.

Assumed envelopes (ADR 026 does not define them; see docs/operations/desktop-console.md):

- ``GET /repos``: ``{"registry_sha256", "repos": [{"repo_id" (or "id"), "baseline_refs", "default_baseline_ref",
  "deploy"}]}``
- ``GET /runs/{id}/repos``: ``{"run_id", "bindings_sha256", "repos" (or "bindings"): [run_repo_bindings row],
  "attempt_worktrees": [row], "commits" (or "attempt_repo_commits"): [row]}``
- ``GET /runs/{id}/candidate-manifests``: ``{"manifests": [{"manifest_sha256", "version", "seq", "created_at",
  "invalidations": [{"reason", "actor", "at"}]}]}``
- ``GET /runs/{id}/candidate-manifests/{sha}``: ``{"manifest_sha256", "manifest": <manifest v1 or v2 object>,
  "invalidations": [...], "diffs": [{"repo_id", "diff", "truncated"}]}``
"""
from __future__ import annotations

import hashlib
import re

MAX_REPOS = 16  # ADR 026 D1 / D8 limit; more rows than this are dropped and counted
MAX_ROWS = 200  # worktree and commit rows read per response
MAX_INVALIDATIONS = 20
MAX_VALIDATIONS = 32
MAX_MANIFESTS = 100
MAX_DIFF_CHARS = 60000
MAX_DIFF_LINES = 4000
MAX_TEXT = 200

DEPLOY_NONE_TEXT = "generated by the pipeline, not deployed by Synapse"
UNCHANGED_TEXT = "unchanged (candidate = baseline)"
READ_TEXT = "read only (pinned baseline)"

COMMIT_STATES = {  # ADR 026 D6 / D10 attempt_repo_commits.state
    "intent": "commit in progress",
    "done": "changed",
    "unchanged": UNCHANGED_TEXT,
    "failed": "commit failed",
    "not_done": "not committed",
    "unknown": "unknown after a crash (needs recovery)",
}
INVALIDATION_REASONS = {  # ADR 026 D2 / D10 candidate_manifest_invalidations.reason
    "baseline_moved": "a baseline ref moved after the run pinned it",
    "candidate_invalid": "a candidate commit is no longer valid",
    "operator": "invalidated by the operator",
}

_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}")
_REF = re.compile(r"refs/[A-Za-z0-9._/-]{1,200}")
_SHA = re.compile(r"[0-9a-f]{40}|[0-9a-f]{64}")
_SHA256 = re.compile(r"[0-9a-f]{64}")
_UNSAFE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f-\x9f؜​-‏‪-‮⁦-⁩﻿]")  # keeps \t \n


def text(value, limit: int = MAX_TEXT) -> str:
    """Plain, bounded text: control, C1 and bidi-override characters removed; non-strings become ''."""
    if not isinstance(value, str):
        return ""
    return _UNSAFE.sub("", value.replace("\r\n", "\n").replace("\r", "\n"))[:limit]


def ident(value) -> str | None:
    return value if isinstance(value, str) and _ID.fullmatch(value) else None


def ref(value) -> str | None:
    return value if isinstance(value, str) and _REF.fullmatch(value) and ".." not in value else None


def sha(value) -> str | None:
    return value if isinstance(value, str) and _SHA.fullmatch(value) else None


def short(value: str | None) -> str:
    return value[:12] if value else "-"


def _int(value) -> int | None:
    return value if type(value) is int and value >= 0 else None


def _rows(value, limit: int = MAX_ROWS) -> list[dict]:
    return [row for row in value[:limit] if isinstance(row, dict)] if isinstance(value, list) else []


def _first(raw: dict, *keys):
    for key in keys:
        if key in raw:
            return raw[key]
    return None


# ------------------------------------------------------------------ sanitizers (None = shape not understood)
def sanitize_registry(raw) -> dict | None:
    """``GET /repos``: registry entries by id with their deploy marker; paths are never read."""
    if not isinstance(raw, dict) or not isinstance(raw.get("repos"), list):
        return None
    entries, dropped = {}, 0
    for row in raw["repos"][:MAX_ROWS]:
        repo_id = ident(_first(row, "repo_id", "id")) if isinstance(row, dict) else None
        if repo_id is None or repo_id in entries or len(entries) >= MAX_REPOS:
            dropped += 1
            continue
        refs = [r for r in (ref(x) for x in (row.get("baseline_refs") if isinstance(row.get("baseline_refs"), list) else [])[:16]) if r]
        entries[repo_id] = {"repo_id": repo_id, "baseline_refs": refs, "default_baseline_ref": ref(row.get("default_baseline_ref")),
                            "deploy_none": row.get("deploy") == "none"}
    dropped += max(0, len(raw["repos"]) - MAX_ROWS)
    return {"registry_sha256": sha(raw.get("registry_sha256")), "repos": entries, "dropped": dropped}


def _commit_row(row: dict) -> dict | None:
    repo_id, state = ident(row.get("repo_id")), row.get("state")
    if repo_id is None or not isinstance(state, str):
        return None
    return {"attempt_id": text(row.get("attempt_id"), 128), "repo_id": repo_id, "seq": _int(row.get("seq")),
            "state": state if state in COMMIT_STATES else "other", "raw_state": text(state, 40),
            "candidate_sha": sha(row.get("candidate_sha")), "reason": text(row.get("reason"), MAX_TEXT)}


def sanitize_run_repos(raw, run_id: str | None = None) -> dict | None:
    """``GET /runs/{id}/repos``: bindings (the run's repository set), worktrees and the latest commit state per repo."""
    if not isinstance(raw, dict):
        return None
    bindings_raw = _first(raw, "repos", "bindings")
    if not isinstance(bindings_raw, list):
        return None
    if run_id is not None and raw.get("run_id") is not None and raw.get("run_id") != run_id:
        return None
    bindings, dropped = {}, 0
    for row in bindings_raw[:MAX_ROWS]:
        repo_id = ident(row.get("repo_id")) if isinstance(row, dict) else None
        if repo_id is None or repo_id in bindings or len(bindings) >= MAX_REPOS:
            dropped += 1
            continue
        writer = row.get("writer_task_id")
        access = row.get("access") if row.get("access") in ("read", "write") else ("read" if writer is None and "writer_task_id" in row else
                                                                                   "write" if isinstance(writer, str) else "unknown")
        bindings[repo_id] = {"repo_id": repo_id, "access": access, "baseline_ref": ref(row.get("baseline_ref")),
                             "baseline_sha": sha(row.get("baseline_sha")), "writer_task_id": text(writer, 128) or None,
                             "deploy_none": row.get("deploy") == "none"}
    dropped += max(0, len(bindings_raw) - MAX_ROWS)
    worktrees = {}
    for row in _rows(raw.get("attempt_worktrees")):
        repo_id = ident(row.get("repo_id"))
        if repo_id is not None:  # the last row per repository is the newest attempt's worktree
            worktrees[repo_id] = {"branch": text(row.get("branch"), MAX_TEXT), "path": text(row.get("path"), 400),
                                  "access": row.get("access") if row.get("access") in ("read", "write") else None}
    commits = {}
    for row in _rows(_first(raw, "commits", "attempt_repo_commits")):
        parsed = _commit_row(row)
        if parsed is not None:  # rows are append-only transitions; the last one per repository is current
            commits[parsed["repo_id"]] = parsed
    return {"bindings_sha256": sha(raw.get("bindings_sha256")), "bindings": bindings, "worktrees": worktrees,
            "commits": commits, "dropped": dropped}


def _invalidations(value) -> list[dict]:
    out = []
    for row in _rows(value, MAX_INVALIDATIONS):
        reason = row.get("reason")
        if isinstance(reason, str):
            known = reason in INVALIDATION_REASONS
            out.append({"reason": reason if known else "other", "text": INVALIDATION_REASONS[reason] if known else
                        "invalidated (" + (text(reason, 60) or "no reason given") + ")", "at": text(row.get("at"), 40)})
    return out


def sanitize_manifest_list(raw) -> list[dict] | None:
    """``GET /runs/{id}/candidate-manifests``: newest last (by ``seq`` when present, else response order)."""
    if not isinstance(raw, dict) or not isinstance(raw.get("manifests"), list):
        return None
    out = []
    for index, row in enumerate(_rows(raw["manifests"], MAX_MANIFESTS)):
        digest = row.get("manifest_sha256")
        if isinstance(digest, str) and _SHA256.fullmatch(digest):
            seq = _int(row.get("seq"))
            out.append({"manifest_sha256": digest, "version": _int(row.get("version")), "order": (seq if seq is not None else -1, index),
                        "invalidations": _invalidations(row.get("invalidations"))})
    out.sort(key=lambda m: m["order"])
    return out


def sanitize_diff(value, truncated_flag=False) -> dict:
    """Untrusted agent diff: plain text, at most MAX_DIFF_LINES lines and MAX_DIFF_CHARS characters."""
    raw = value if isinstance(value, str) else ""
    cleaned = text(raw[:MAX_DIFF_CHARS * 2], MAX_DIFF_CHARS + 1)
    lines = cleaned.split("\n")
    truncated = truncated_flag is True or len(raw) > MAX_DIFF_CHARS * 2 or len(cleaned) > MAX_DIFF_CHARS or len(lines) > MAX_DIFF_LINES
    shown = "\n".join(lines[:MAX_DIFF_LINES])[:MAX_DIFF_CHARS]
    return {"text": shown, "truncated": truncated, "raw_sha256": hashlib.sha256(raw.encode("utf-8", "surrogatepass")).hexdigest()}


def _validations(value) -> list[dict]:
    out = []
    for row in _rows(value, MAX_VALIDATIONS):
        name = ident(row.get("name"))
        if name is not None:
            outcome = row.get("outcome")
            out.append({"name": name, "outcome": outcome if outcome in ("passed", "failed", "skipped") else "unknown"})
    return out


def sanitize_manifest_detail(raw, run_id: str | None = None) -> dict | None:
    """``GET /runs/{id}/candidate-manifests/{sha}``: manifest v1 or v2 plus diffs, invalidations and local findings.

    ``problems`` are what this client could check without the canonical bytes (it never claims the hash is right)."""
    if not isinstance(raw, dict):
        return None
    manifest = raw.get("manifest") if isinstance(raw.get("manifest"), dict) else raw
    digest = raw.get("manifest_sha256")
    if not isinstance(manifest.get("repos"), list) or not (isinstance(digest, str) and _SHA256.fullmatch(digest)):
        return None
    version = _int(manifest.get("v"))
    problems = []
    if version not in (1, 2):
        problems.append("unknown manifest version")
    if run_id is not None and manifest.get("run_id") != run_id:
        problems.append("manifest names a different run")
    diffs = {}
    for row in _rows(raw.get("diffs"), MAX_REPOS):
        repo_id = ident(row.get("repo_id"))
        if repo_id is not None and repo_id not in diffs:
            diffs[repo_id] = sanitize_diff(row.get("diff"), row.get("truncated"))
    entries, ids = [], []
    for row in manifest["repos"][:MAX_REPOS * 4]:
        repo_id = ident(row.get("repo_id")) if isinstance(row, dict) else None
        if repo_id is None:
            problems.append("an entry has no valid repo_id")
            continue
        ids.append(repo_id)
        access = row.get("access") if row.get("access") in ("read", "write") else ("write" if version == 1 else "unknown")
        baseline, candidate = sha(row.get("baseline_sha")), sha(row.get("candidate_sha"))
        source = row.get("source") if isinstance(row.get("source"), dict) else {}
        diff_sha = row.get("diff_sha256") if isinstance(row.get("diff_sha256"), str) and _SHA256.fullmatch(row["diff_sha256"]) else None
        diff = diffs.get(repo_id)
        if diff is not None:  # an untruncated diff whose UTF-8 hash equals diff_sha256 is the diff the manifest binds
            diff = dict(diff, verified=(not diff["truncated"] and diff_sha is not None and diff["raw_sha256"] == diff_sha))
        validations = _validations(row.get("validations"))
        entries.append({"repo_id": repo_id, "access": access, "baseline_ref": ref(row.get("baseline_ref")), "baseline_sha": baseline,
                        "candidate_sha": candidate, "unchanged": access == "write" and baseline is not None and baseline == candidate,
                        "source_task": text(source.get("task_id"), 128) or None, "source_attempt": _int(source.get("attempt_no")),
                        "diff_sha256": diff_sha, "diff_bytes": _int(row.get("diff_bytes")), "changed_paths": _int(row.get("changed_paths")),
                        "validations": validations, "diff": diff})
        if access == "write" and any(v["outcome"] != "passed" for v in validations):
            problems.append(f"{repo_id}: a validation did not pass")
    if len(manifest["repos"]) > MAX_REPOS:
        problems.append(f"more than {MAX_REPOS} repositories")
    if ids != sorted(ids) or len(set(ids)) != len(ids):
        problems.append("repositories are not sorted by repo_id or not unique")
    writes = [e for e in entries if e["access"] == "write"]
    if version == 2 and writes and all(e["unchanged"] for e in writes):
        problems.append("no write repository changed (no_changes)")
    return {"manifest_sha256": digest, "version": version, "bindings_sha256": sha(manifest.get("bindings_sha256")),
            "entries": entries, "invalidations": _invalidations(raw.get("invalidations")), "problems": problems[:20]}


# ------------------------------------------------------------------ composition
def _state(entry: dict | None, commit: dict | None, access: str) -> tuple[str, str]:
    if access == "read":
        return "read", READ_TEXT
    if entry is not None and entry["candidate_sha"] is not None:
        return ("unchanged", UNCHANGED_TEXT) if entry["unchanged"] else ("changed", "changed")
    if commit is not None:
        label = COMMIT_STATES.get(commit["state"], "state " + (commit["raw_state"] or "unknown"))
        if commit["state"] == "failed" and commit["reason"]:
            label += ": " + commit["reason"]
        return commit["state"], label
    return "pending", "no commit yet"


def build_view(run_repos: dict | None, manifests: list[dict] | None, detail: dict | None, registry: dict | None = None) -> dict:
    """Merge the sanitized reads into per-repository rows plus a manifest summary.

    ``visible`` is True only for a run with more than one repository or with a manifest; a single-repository run on
    an old daemon (every route 404) keeps today's agent pane alone."""
    bindings = (run_repos or {}).get("bindings") or {}
    entries = {e["repo_id"]: e for e in (detail or {}).get("entries", [])}
    commits = (run_repos or {}).get("commits") or {}
    worktrees = (run_repos or {}).get("worktrees") or {}
    registry_repos = (registry or {}).get("repos") or {}
    rows = []
    for repo_id in sorted(set(bindings) | set(entries))[:MAX_REPOS]:
        binding, entry = bindings.get(repo_id), entries.get(repo_id)
        access = (binding or {}).get("access") or "unknown"
        if access == "unknown" and entry is not None:
            access = entry["access"]
        state, label = _state(entry, commits.get(repo_id), access)
        deploy_none = bool((binding or {}).get("deploy_none") or (registry_repos.get(repo_id) or {}).get("deploy_none"))
        rows.append({"repo_id": repo_id, "access": access, "state": state, "label": label,
                     "baseline_ref": (binding or {}).get("baseline_ref") or (entry or {}).get("baseline_ref"),
                     "baseline_sha": (binding or {}).get("baseline_sha") or (entry or {}).get("baseline_sha"),
                     "candidate_sha": (entry or {}).get("candidate_sha"), "deploy_none": deploy_none,
                     "deploy": DEPLOY_NONE_TEXT if deploy_none else ("-" if access != "write" else "per deploy target"),
                     "branch": (worktrees.get(repo_id) or {}).get("branch") or "",
                     "changed_paths": (entry or {}).get("changed_paths"), "diff_bytes": (entry or {}).get("diff_bytes"),
                     "validations": (entry or {}).get("validations") or [], "diff": (entry or {}).get("diff")})
    manifest = None
    if detail is not None:
        listed = next((m for m in manifests or [] if m["manifest_sha256"] == detail["manifest_sha256"]), None)
        invalidations = detail["invalidations"] or (listed or {}).get("invalidations") or []
        if (run_repos or {}).get("bindings_sha256") and detail["bindings_sha256"] and run_repos["bindings_sha256"] != detail["bindings_sha256"]:
            detail = dict(detail, problems=detail["problems"] + ["bindings_sha256 differs from the run's bindings"])
        manifest = {"manifest_sha256": detail["manifest_sha256"], "version": detail["version"], "invalidations": invalidations,
                    "problems": detail["problems"], "count": len(manifests or []),
                    "validity": "invalidated" if invalidations else ("problems" if detail["problems"] else "valid")}
    elif manifests:
        newest = manifests[-1]
        manifest = {"manifest_sha256": newest["manifest_sha256"], "version": newest["version"], "invalidations": newest["invalidations"],
                    "problems": ["manifest detail not available"], "count": len(manifests),
                    "validity": "invalidated" if newest["invalidations"] else "unknown"}
    dropped = (run_repos or {}).get("dropped", 0)
    return {"visible": len(rows) > 1 or manifest is not None, "rows": rows, "manifest": manifest, "dropped": dropped,
            "bindings_sha256": (run_repos or {}).get("bindings_sha256")}


def manifest_summary(manifest: dict | None) -> tuple[str, str]:
    """(headline, banner) plain text for the manifest; banner is '' unless the manifest must not be acted on."""
    if manifest is None:
        return "No candidate manifest yet.", ""
    head = f"Candidate manifest {short(manifest['manifest_sha256'])} (v{manifest['version'] if manifest['version'] is not None else '?'})"
    if manifest["count"] > 1:
        head += f", newest of {manifest['count']}"
    if manifest["validity"] == "invalidated":
        reasons = "; ".join(sorted({i["text"] for i in manifest["invalidations"]}))
        return head + ": INVALIDATED", "This manifest is invalidated and cannot be approved or deployed: " + reasons + "."
    if manifest["validity"] == "problems":
        return head + ": not usable", "This view found problems in the manifest: " + "; ".join(manifest["problems"]) + "."
    if manifest["validity"] == "unknown":
        return head + ": details not available", ""
    return head + ": valid (no invalidation recorded by the daemon)", ""
