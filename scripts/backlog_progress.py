#!/usr/bin/env python3
"""Progress counters for IMPLEMENTATION_BACKLOG.md.

Counts ``- [x]`` / ``- [ ]`` checkboxes per level-2 heading (level-3 headings roll up into their parent;
fenced code and the generated block are ignored). Headings without checkboxes are skipped. Also counts
security findings (``- F<n> [fixed|open]``) and open PRs (``- #<n> [draft|ready]``) listed in the file.

    backlog_progress.py            print the generated block
    backlog_progress.py --write    rewrite the block between the markers
    backlog_progress.py --check    exit 1 if the block in the file is stale
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

START = "<!-- progress:start -->"
END = "<!-- progress:end -->"
BAR_WIDTH = 20
_BOX = re.compile(r"^\s*- \[( |x|X)\] ")
_FINDING = re.compile(r"^\s*- (F\d+) \[(fixed|open)\]")
_PR = re.compile(r"^\s*- #(\d+) \[(draft|ready)\]")


def strip_block(text: str) -> str:
    """The document without the generated block (so the block never counts itself)."""
    i, j = text.find(START), text.find(END)
    if i == -1 or j == -1 or j < i:
        return text
    return text[:i] + text[j + len(END):]


def _lines(text: str):
    fenced = False
    for line in strip_block(text).splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            yield line


def count_milestones(text: str) -> list[tuple[str, int, int]]:
    """[(heading, done, total)] for each ``## `` heading that has at least one checkbox."""
    rows: list[list] = []
    current = None
    for line in _lines(text):
        if line.startswith("## "):
            current = [line[3:].strip(), 0, 0]
            rows.append(current)
        elif current is not None and (m := _BOX.match(line)):
            current[2] += 1
            current[1] += m.group(1) in "xX"
    return [(h, d, t) for h, d, t in rows if t]


def count_findings(text: str) -> tuple[int, int]:
    found = {m.group(1): m.group(2) for line in _lines(text) if (m := _FINDING.match(line))}
    return sum(v == "fixed" for v in found.values()), sum(v == "open" for v in found.values())


def count_prs(text: str) -> tuple[int, int]:
    found = {m.group(1): m.group(2) for line in _lines(text) if (m := _PR.match(line))}
    return sum(v == "draft" for v in found.values()), sum(v == "ready" for v in found.values())


def pct(done: int, total: int) -> int:
    return (100 * done + total // 2) // total if total else 0


def bar(done: int, total: int) -> str:
    filled = (BAR_WIDTH * done) // total if total else 0
    return f"[{'#' * filled}{'-' * (BAR_WIDTH - filled)}] {pct(done, total)}%"


def render(text: str) -> str:
    rows = count_milestones(text)
    done, total = sum(r[1] for r in rows), sum(r[2] for r in rows)
    out = [START, "", "| Milestone | Done | Total | % |", "| --- | ---: | ---: | ---: |"]
    for heading, d, t in rows:
        out.append(f"| {heading} | {d} | {t} | {pct(d, t)}% |")
    out.append(f"| **Overall** | **{done}** | **{total}** | **{pct(done, total)}%** |")
    fixed, opened = count_findings(text)
    drafts, ready = count_prs(text)
    out += [
        "",
        "```text",
        f"Overall  {bar(done, total)}  ({done}/{total} checkboxes)",
        "```",
        "",
        f"Security findings F1-F14: {fixed} fixed, {opened} open (list under M7.5).",
        f"Open PRs: {drafts + ready} ({drafts} draft, {ready} ready for review; list at the end of this file).",
        "",
        "Generated by `scripts/backlog_progress.py --write`; `--check` (and `tests/test_backlog_progress.py`) fail when it is stale.",
        "",
        END,
    ]
    return "\n".join(out)


def update(text: str) -> str:
    i, j = text.find(START), text.find(END)
    if i == -1 or j == -1 or j < i:
        raise SystemExit(f"markers {START} / {END} not found")
    return text[:i] + render(text) + text[j + len(END):]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--file", type=Path, default=Path(__file__).resolve().parent.parent / "IMPLEMENTATION_BACKLOG.md")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    text = args.file.read_text(encoding="utf-8")
    if args.check:
        if update(text) != text:
            print(f"{args.file.name}: progress table is stale; run scripts/backlog_progress.py --write", file=sys.stderr)
            return 1
        return 0
    if args.write:
        args.file.write_text(update(text), encoding="utf-8")
        return 0
    print(render(text))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
